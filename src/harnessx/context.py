'''Context compaction.

Invariants: keep system + original task (messages[0:2]); keep the most recent `keep_turns` TURNS verbatim (a turn is
one assistant message plus all of its tool results, so the cut can never fall inside a tool_call/tool batch and the
newest results are never summarized before the model has seen them); the middle becomes ONE user message that starts
with MARK so it is clearly a harness-made summary. Every compaction is logged as a `compaction` event with before/after
token estimates (replayed on resume, used for metrics).

Two summarizers:
  * rule: deterministic, free; lists actions, files written/read, errors. It does NOT copy tool output, so
    facts that only lived in tool output are lost.
  * llm: asks the model for a fact-preserving summary; its token usage is reported via pending_usage and charged.

estimate_tokens is a rough heuristic (serialized chars / 3, plus 4 per message), not a tokenizer.
'''
from __future__ import annotations

import json

MARK = '[CONTEXT SUMMARY generated by harness; these are not original messages]'

LLM_SUMMARY_PROMPT = ('You compress the middle of an agent transcript so the agent can continue without it. '
                      'Write a concise summary that preserves every concrete fact needed to finish the task: values '
                      'found in tool outputs (codes, numbers, names, paths), files created or edited, what has been '
                      'verified, errors and what is still left to do. Do not invent facts. Plain text, no preamble.')


def estimate_tokens(messages: list) -> int:
    return sum(len(json.dumps(m, ensure_ascii=False)) for m in messages) // 3 + 4 * len(messages)


def turn_starts(messages: list) -> list:
    '''Indexes (>= 2) where a turn starts: an assistant message, or a user message (e.g. a prior summary).'''
    return [i for i in range(2, len(messages)) if messages[i].get('role') in ('assistant', 'user')]


def summarize(middle: list, max_lines: int = 40) -> str:
    calls, lines, wrote, read, errors = {}, [], [], [], []
    prior = ''
    for m in middle:
        role = m.get('role')
        if role == 'user' and str(m.get('content', '')).startswith(MARK):
            prior = str(m['content'])[len(MARK):].strip()
            while prior.startswith('Earlier summary (carried forward):'):
                prior = prior[len('Earlier summary (carried forward):'):].strip()
            prior = prior[-1500:]
        elif role == 'assistant':
            for tc in m.get('tool_calls') or []:
                fn = tc.get('function') or {}
                try:
                    a = json.loads(fn.get('arguments') or '{}')
                except Exception:
                    a = {}
                calls[tc.get('id')] = (fn.get('name'), a if isinstance(a, dict) else {})
            t = (m.get('content') or '').strip()
            if t:
                lines.append('assistant said: ' + t[:160].replace('\n', ' '))
        elif role == 'tool':
            name, a = calls.get(m.get('tool_call_id'), ('?', {}))
            try:
                r = json.loads(m.get('content') or '{}')
            except Exception:
                r = {}
            rc = r.get('returncode') if isinstance(r, dict) else None
            target = a.get('path') or str(a.get('command') or a.get('code') or '')[:60].replace('\n', ' ')
            lines.append('%s(%s) -> rc=%s' % (name, target, rc))
            if name in ('write_file', 'edit_file') and rc == 0 and a.get('path'):
                wrote.append(a['path'])
            if name == 'read_file' and a.get('path'):
                read.append(a['path'])
            if rc not in (0, None):
                errors.append('%s(%s): %s' % (name, target, str((r.get('error') or r.get('output') or ''))[:120].replace('\n', ' ')))
    parts = []
    if prior:
        parts.append('Earlier summary (carried forward):\n' + prior)
    if len(lines) > max_lines:
        parts.append('(%d older actions omitted)' % (len(lines) - max_lines))
        lines = lines[-max_lines:]
    parts.append('Actions in the summarized span:\n' + '\n'.join(lines))
    parts.append('Files written/edited: ' + (', '.join(dict.fromkeys(wrote)) or 'none'))
    parts.append('Files read: ' + (', '.join(dict.fromkeys(read)) or 'none'))
    if errors:
        parts.append('Errors seen: ' + ' | '.join(errors[-5:]))
    return '\n'.join(parts)


def serialize_for_summary(messages: list, task: str, per_msg: int = 6000) -> str:
    out = ['TASK: ' + str(task)[:2000], '--- transcript span to summarize ---']
    for m in messages:
        role = m.get('role')
        if role == 'assistant':
            calls = ['%s(%s)' % ((tc.get('function') or {}).get('name'), str((tc.get('function') or {}).get('arguments'))[:300])
                     for tc in m.get('tool_calls') or []]
            out.append('ASSISTANT: %s %s' % ((m.get('content') or '')[:per_msg], ' '.join(calls)))
        else:
            out.append('%s: %s' % (role.upper(), str(m.get('content') or '')[:per_msg]))
    return '\n'.join(out)


class Compactor:
    def __init__(self, limit: int, keep_turns: int = 2, model=None):
        self.limit, self.keep_turns, self.model = limit, keep_turns, model
        self.pending_usage: dict = {}

    def _summary(self, middle: list, task: str):
        if self.model is None:
            return summarize(middle), 'rule', {}
        r = self.model.chat([{'role': 'system', 'content': LLM_SUMMARY_PROMPT},
                             {'role': 'user', 'content': serialize_for_summary(middle, task)}], [])
        text = (r['message'].get('content') or '').strip()
        if not text:
            return summarize(middle), 'rule(fallback: empty llm summary)', r.get('usage') or {}
        return text, 'llm', r.get('usage') or {}

    def maybe_compact(self, messages: list, log=None, step: int = 0) -> list:
        self.pending_usage = {}
        if self.limit <= 0:
            return messages
        before = estimate_tokens(messages)
        if before <= self.limit:
            return messages
        starts = turn_starts(messages)
        if len(starts) <= self.keep_turns:
            return messages
        tail = starts[-self.keep_turns] if self.keep_turns > 0 else len(messages)
        middle = messages[2:tail]
        if not middle or (len(middle) == 1 and str(middle[0].get('content', '')).startswith(MARK)):
            return messages
        try:
            text, kind, usage = self._summary(middle, messages[1].get('content', ''))
        except Exception as e:  # summarizer failure must not kill the run
            text, kind, usage = summarize(middle), 'rule(fallback: %s)' % type(e).__name__, {}
        self.pending_usage = usage
        summary = {'role': 'user', 'content': MARK + '\n' + text}
        new = messages[:2] + [summary] + messages[tail:]
        after = estimate_tokens(new)
        if after >= before:
            return messages
        if log is not None:
            log.emit('compaction', {'step': step, 'limit': self.limit, 'summarizer': kind, 'summary_usage': usage,
                                    'before_tokens': before, 'after_tokens': after,
                                    'before_messages': len(messages), 'after_messages': len(new),
                                    'dropped': len(middle), 'summary_message': summary})
        return new
